# ---------------- 분류 ----------------
_GENERIC = {"H1", "H5", "F4", "P4", "R2", "F1", "G1", None}  # 슈퍼컴 요구서에서는 슈퍼컴 쪽으로 끌어오는 일반 카테고리
_AMBIGUOUS_HOW = {"제목 기준", "같은 요구서", "미분류"}
_CONTEXT_OK = {"법률검토"}  # 세부 키워드를 상위 제목에서도 찾는 업무


def _sc_rule(text: str, allt: str) -> str | None:
    if not re.search(SC, allt) or re.search(r"원장 결재|기관장", text):
        return None
    if re.search(S3_TERMS, text):
        return "S3"
    if re.search(S2_STRONG, text):
        return "S2"
    if re.search(S1_TERMS, text):
        return "S1"
    return "S2" if re.search(r"6호기|한강", allt) else "S1"


def classify(text: str, context: str = "", title: str = "") -> tuple[str | None, str]:
    """(카테고리, 방법). 방법: 규칙(질의 문장) / 상위 제목 / 제목 기준 / 미분류."""
    allt = " ".join([title or "", context or "", text])
    for code, pat, scope, excl in RULES:
        if code == "SC":
            got = _sc_rule(text, allt)
            if got:
                return got, "규칙"
            continue
        target = allt if scope == "all" else (text + " " + (context or "") if scope == "all_text" else text)
        if re.search(pat, target) and not (excl and re.search(excl, text)):
            return code, "규칙"
    for target, how in ((f"{context} {text}", "상위 제목"), (allt, "제목 기준")):
        if how == "상위 제목" and not context:
            continue
        for code, pat, _scope, excl in RULES:
            if code in ("SC", "X1"):
                continue
            if re.search(pat, target) and not (excl and re.search(excl, text)):
                return code, how
    return None, "미분류"


def route(cat: str, text: str, context: str = "", excluded=frozenset()) -> tuple[str, str, str]:
    """(부서, 업무, 걸린 세부 키워드). 질의 문장 → (일부 업무는) 상위 제목 → 기본 담당 순.

    excluded: 담당자 설정에서 뺀 "부서|업무" — 그 줄은 건너뛰고 다음 줄(없으면 기본 담당)로 간다.
    """
    rows = [r for r in TABLE if r[0] == cat and f"{r[2]}|{r[3]}" not in excluded]
    for target in (text, context):
        for _, cond, dept, task in rows:
            if target is context and task not in _CONTEXT_OK:
                continue
            if cond and target and (m := re.search(cond, target)):
                return dept, task, m.group(0)
    for _, cond, dept, task in rows:
        if cond is None:
            return dept, task, ""
    return "", "", ""


def assign(items: list[dict], use_siblings: bool = True, excluded=frozenset(), custom=()) -> list[dict]:
    """items(text·context·title)에 cat·how·dept·task·why·ambiguous를 채운다.

    use_siblings=False: 공통요구자료처럼 성격이 제각각인 질의 묶음은 다수결 보완을 쓰지 않는다.
    excluded: 배분에서 뺀 "부서|업무", custom: 추가 업무 [{dept, task, keywords}] — 키워드가 있으면 먼저 적용.
    """
    det = [classify(it["text"], it.get("context", ""), it.get("title", "")) for it in items]
    votes = Counter(c for c, how in det if c and how == "규칙")
    sc_major = sum(c in ("S1", "S2", "S3") for c, _ in det) >= max(1, len(det) / 2)
    for it, (cat, how) in zip(items, det):
        if sc_major and cat in _GENERIC:
            cat, how = _sc_rule(it["text"], "슈퍼컴 " + it["text"]), "같은 요구서(슈퍼컴)"
        elif not cat and use_siblings and votes:
            cat, how = votes.most_common(1)[0][0], "같은 요구서"
        dept, task, kw = route(cat, it["text"], it.get("context", ""), excluded) if cat else ("", "", "")
        ambiguous = how in _AMBIGUOUS_HOW or cat == "X1" or not dept  # 업무를 모두 빼 갈 곳이 없으면 확인 필요
        added = next(((c, k) for c in custom for k in c["keywords"] if k in it["text"]), None)
        if added:
            (c, k), ambiguous = added, False
            dept, task, why = c["dept"], c["task"], f"‘{k}’ 추가 업무"
        elif ambiguous:
            why = "공통자료요구 — 첨부 확인 후 배분" if cat == "X1" else (f"추정: {dept}" if dept else "추정 부서 없음")
            dept, task = DEFAULT_DEPT, ""
        else:
            why = f"‘{kw}’ 키워드" if kw else ""
        it.update(cat=cat, cat_name=CATS[cat][1] if cat else "(미분류)", how=how, dept=dept or DEFAULT_DEPT,
                  task=task, why=why, ambiguous=ambiguous)
    return items


# ---------------- 요구서 → 배분 단위 질의 ----------------
_NUM = re.compile(r"^\s*(\d+)\s*[.)]\s*")
# 질의 끝에 붙는 안내·연락처 (배분 대상 아님)
_NOTE_CUT = re.compile(r"\s*※\s*(성명 등 개인정보|자료 제출 관련 문의|시스템과 메일)")
_TOP_ITEM = re.compile(r"^(\d+)\.\s*(?:\[([^\]]+)\]\s*)?(.*)$", re.S)
_SUB_ITEM = re.compile(r"^(\d+-\d+)\)\s*\[(?:\[([^\]]+)\]\s*)?([^\]]*)\]\s*(.*)$", re.S)


def request_items(items: list[str]) -> tuple[str, list[dict]]:
    """질의서 PDF의 요구내용 항목 → (요구 제목, 질의 목록).

    요구목록 첫 항목 "1. 제목" 아래 세부 질의가 다시 1번부터 붙으면 첫 항목을 제목으로 뗀다.
    """
    items, title = list(items), ""
    first, second = (_NUM.match(items[0]) if items else None), (_NUM.match(items[1]) if len(items) > 1 else None)
    if first and second and first.group(1) == second.group(1) == "1":
        title = _NUM.sub("", items.pop(0).split("※")[0]).strip()
    out = []
    for text in items:
        if m := _NOTE_CUT.search(text):
            text = text[:m.start()]
        num = _NUM.match(text)
        out.append({"key": num.group(1) if num else "-", "section": "", "text": _NUM.sub("", text).strip(),
                    "context": title, "title": title})
    return title, out


def attachment_items(items: list[str], title: str = "") -> list[dict]:
    """첨부 한글파일 항목("3. [연구기관] …", "1-2) [[연구기관] 상위 제목] …") → 질의 목록."""
    out = []
    for raw in items:
        first, *rest = raw.split("\n")
        if m := _SUB_ITEM.match(first):
            key, section, context, body = m.group(1), m.group(2) or "", m.group(3), m.group(4)
        elif m := _TOP_ITEM.match(first):
            key, section, context, body = m.group(1), m.group(2) or "", "", m.group(3)
        else:
            key, section, context, body = "-", "", "", first
        out.append({"key": f"[{section}] {key}" if section else key, "section": section,
                    "text": " / ".join([body, *rest]), "context": context, "title": title})
    return out


def plan(questions: list[dict], use_siblings: bool, excluded=frozenset(), custom=()) -> list[dict]:
    """질의 목록을 배분하고, 비해당 섹션은 해당없음, 같은 요구서 안의 똑같은 질의는 dup_of로 표시한다."""
    use = [q for q in questions if q["section"] in APPLICABLE_SECTIONS]
    assign(use, use_siblings=use_siblings, excluded=excluded, custom=custom)
    for q in questions:
        if q["section"] not in APPLICABLE_SECTIONS:
            q.update(cat=None, cat_name="-", how="-", dept=NA_DEPT, task="", ambiguous=False,
                     why=f"〈{q['section']}〉 섹션 — 우리 기관 비해당")
    seen = {}
    for q in use:
        k = re.sub(r"\s+", "", q["text"])
        if k in seen:
            q["dup_of"] = seen[k]
        else:
            seen[k] = q["key"]
    return questions
